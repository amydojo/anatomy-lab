import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const path=process.env.KINETIC_GLB;
test('KINETIC actual imported asset, replay and inspection metrics',async({page},testInfo)=>{
 test.skip(!path,'Requires exact exported KINETIC asset');
 await page.goto('/experiments/hairpin/?edition=kinetic');
 await page.locator('#vector-file').setInputFiles(path);
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__?.report().ready),{timeout:15000}).toBe(true);
 const rest=await page.evaluate(()=>window.__ATELIER__.report());
 expect(rest.triangles).toBeGreaterThan(100000);
 expect(rest.renderer.drawCalls).toBe(rest.batches);
 await page.locator('#kinetic-play').click();
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__.report().playTime),{timeout:15000}).toBeGreaterThan(1.8);
 await page.locator('#kinetic-speed').selectOption('.5');
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__.report().playTime),{timeout:15000}).toBeGreaterThan(3.4);
 const carve=await page.evaluate(()=>window.__ATELIER__.report());
 expect(carve.playRate).toBe(.5);
 expect(carve.pose.kinetic).toBe(true);
 expect(Math.abs(carve.pose.twist)).toBeLessThanOrEqual(.14);
 await page.locator('#kinetic-play').click();
 await page.locator('[data-state="flight"]').click();
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__.report().pose?.deploy),{timeout:10000}).toBeGreaterThan(.7);
 await page.locator('[data-view="under"]').click();
 await page.screenshot({path:testInfo.outputPath('kinetic-flight-under.png')});
 await page.locator('[data-state="land"]').click();
 await page.locator('[data-state="hover"]').click();
 await page.locator('[data-view="hero"]').click();
 await page.evaluate(()=>window.__ATELIER__.benchmark());
 await page.waitForTimeout(4000);
 const measured=await page.evaluate(()=>window.__ATELIER__.report());
 expect(measured.ready).toBe(true);expect(measured.frameMs.samples).toBeGreaterThan(5);
 fs.writeFileSync(testInfo.outputPath('kinetic-metrics.json'),JSON.stringify({rest,carve,measured},null,2));
 await page.screenshot({path:testInfo.outputPath('kinetic-hero.png')});
 await page.evaluate(()=>window.__ATELIER__.dispose());
 expect(await page.evaluate(()=>window.__ATELIER__.report().ready)).toBe(false);
});
