import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const path=process.env.VELOCITY_GLB;
test('VELOCITY embedded maps and real sustained replay',async({page},info)=>{
 test.skip(!path,'Requires actual baked GLB artifact');
 await page.goto('/experiments/hairpin/?edition=velocity');
 await page.locator('#vector-file').setInputFiles(path);
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__?.report().ready),{timeout:30000}).toBe(true);
 const rest=await page.evaluate(()=>window.__ATELIER__.report());
 expect(rest.renderer.glError).toBe(0);
 expect(rest.renderer.materialContract).toBe('velocity-gltf-pbr-v1');
 expect(rest.renderer.textureBytes).toBeGreaterThan(0);
 expect(rest.renderer.drawCalls).toBeLessThanOrEqual(5);
 expect(rest.triangles).toBeGreaterThan(0);
 await page.screenshot({path:info.outputPath('velocity-hero.png')});
 await page.locator('[data-view="ride"]').click();
 await page.screenshot({path:info.outputPath('velocity-ride.png')});
 await page.locator('[data-view="hero"]').click();
 await page.evaluate(()=>window.__ATELIER__.lighting('game'));
 await page.screenshot({path:info.outputPath('velocity-game.png')});
 await page.evaluate(()=>window.__ATELIER__.lighting('studio'));
 await page.evaluate(()=>window.__ATELIER__.diagnostic(1));
 await page.screenshot({path:info.outputPath('velocity-basecolor.png')});
 await page.evaluate(()=>window.__ATELIER__.diagnostic(0));
 await page.locator('#kinetic-play').click();
 await page.evaluate(()=>window.__ATELIER__.benchmark());
 await page.waitForTimeout(6000);
 const measured=await page.evaluate(()=>window.__ATELIER__.report());
 expect(measured.frameMs.samples).toBeGreaterThan(10);
 expect(measured.renderer.glError).toBe(0);
 expect(measured.playTime).toBeGreaterThan(0);
 await page.locator('#kinetic-play').click();
 await page.locator('[data-state="flight"]').click();
 await expect.poll(()=>page.evaluate(()=>window.__ATELIER__.report().pose?.deploy),{timeout:15000}).toBeGreaterThan(.7);
 await page.locator('[data-view="under"]').click();
 await page.screenshot({path:info.outputPath('velocity-flight.png')});
 await page.locator('[data-state="land"]').click();
 await page.locator('[data-view="hero"]').click();
 await page.screenshot({path:info.outputPath('velocity-land.png')});
 fs.writeFileSync(info.outputPath('velocity-metrics.json'),JSON.stringify({rest,measured,qualification:'inspection only; callback and CPU submission, not GPU timing'},null,2));
 await page.evaluate(()=>window.__ATELIER__.dispose());
 const disposed=await page.evaluate(()=>window.__ATELIER__.report());
 expect(disposed.ready).toBe(false);expect(disposed.renderer.liveTextures).toBe(0);
});
